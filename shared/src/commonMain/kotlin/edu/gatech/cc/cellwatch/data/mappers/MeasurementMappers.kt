package edu.gatech.cc.cellwatch.data.mappers

import edu.gatech.cc.cellwatch.db.MeasurementEntity
import edu.gatech.cc.cellwatch.domain.model.Measurement
import edu.gatech.cc.cellwatch.domain.model.NetworkConnectionType
import kotlinx.datetime.Instant

fun MeasurementEntity.toDomain(): Measurement = Measurement(
    id = id,
    groupId = groupId,
    campaignId = campaignId,
    sessionId = sessionId,
    deviceId = deviceId,
    deviceManufacturer = deviceManufacturer,
    deviceModel = deviceModel,
    deviceOsName = deviceOsName,
    deviceOsVersion = deviceOsVersion,
    appName = appName,
    provider = provider,
    type = type,
    timestamp = timestamp?.let(Instant::fromEpochMilliseconds),
    duration = duration,
    scheduled = scheduled.toBooleanOrNull(),
    success = success.toBooleanOrNull(),
    carrierAggregation = carrierAggregation.toBooleanOrNull(),
    networkConnected = networkConnected.toBooleanOrNull(),
    networkAvailable = networkAvailable.toBooleanOrNull(),
    networkRoaming = networkRoaming.toBooleanOrNull(),
    simMcc = simMcc,
    simMnc = simMnc,
    netMcc = netMcc,
    netMnc = netMnc,
    telephonySupport = telephonySupport,
    networkSupport = networkSupport,
    locationSupport = locationSupport,
    deviceSupport = deviceSupport,
    capabilityNotes = capabilityNotes,
    extraData = extraData,
    createdOn = createdOn?.let(Instant::fromEpochMilliseconds),
    updatedOn = updatedOn?.let(Instant::fromEpochMilliseconds),
    connectionType = connectionType?.let(NetworkConnectionType::valueOf),
    cellularDataEnabled = cellularDataEnabled.toBooleanOrNull(),
    uploadTime = uploadTime?.let(Instant::fromEpochMilliseconds),
    appVersion = appVersion,
)

fun Measurement.toRow(): MeasurementEntity = MeasurementEntity(
    id = id,
    groupId = groupId,
    campaignId = campaignId,
    sessionId = sessionId,
    deviceId = deviceId,
    deviceManufacturer = deviceManufacturer,
    deviceModel = deviceModel,
    deviceOsName = deviceOsName,
    deviceOsVersion = deviceOsVersion,
    appName = appName,
    provider = provider,
    type = type,
    timestamp = timestamp?.toEpochMilliseconds(),
    duration = duration,
    scheduled = scheduled.toSqlBoolean(),
    success = success.toSqlBoolean(),
    carrierAggregation = carrierAggregation.toSqlBoolean(),
    networkConnected = networkConnected.toSqlBoolean(),
    networkAvailable = networkAvailable.toSqlBoolean(),
    networkRoaming = networkRoaming.toSqlBoolean(),
    simMcc = simMcc,
    simMnc = simMnc,
    netMcc = netMcc,
    netMnc = netMnc,
    telephonySupport = telephonySupport,
    networkSupport = networkSupport,
    locationSupport = locationSupport,
    deviceSupport = deviceSupport,
    capabilityNotes = capabilityNotes,
    connectionType = connectionType?.name,
    cellularDataEnabled = cellularDataEnabled.toSqlBoolean(),
    extraData = extraData,
    createdOn = createdOn?.toEpochMilliseconds(),
    updatedOn = updatedOn?.toEpochMilliseconds(),
    uploadTime = uploadTime?.toEpochMilliseconds(),
    appVersion = appVersion,
)
