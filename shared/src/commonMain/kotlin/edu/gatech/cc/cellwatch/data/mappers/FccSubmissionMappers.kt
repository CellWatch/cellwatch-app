package edu.gatech.cc.cellwatch.data.mappers

import edu.gatech.cc.cellwatch.db.FccSubmissionEntity
import edu.gatech.cc.cellwatch.domain.model.FccSubmission
import kotlinx.datetime.Instant

fun FccSubmissionEntity.toDomain(): FccSubmission = FccSubmission(
    id = id,
    challengeDataId = challengeDataId,
    contactName = contactName,
    contactEmail = contactEmail,
    contactPhone = contactPhone,
    deviceTimestamp = deviceTimestamp?.let(Instant::fromEpochMilliseconds),
    serverTimestamp = serverTimestamp?.let(Instant::fromEpochMilliseconds),
    sourceIp = sourceIp,
    sourcePort = sourcePort?.toInt(),
    deviceId = deviceId,
    deviceImei = deviceImei,
    deviceTac = deviceTac,
    deviceType = deviceType,
    deviceManufacturer = deviceManufacturer,
    deviceModel = deviceModel,
    deviceOsName = deviceOsName,
    appName = appName,
    appVersion = appVersion,
    provider = provider,
    simCountryCode = simCountryCode,
    simNetworkCode = simNetworkCode,
    netCountryCode = netCountryCode,
    netNetworkCode = netNetworkCode,
    inVehicle = inVehicle.toBooleanOrNull(),
    externalAntenna = externalAntenna.toBooleanOrNull(),
    submitted = submitted.toBooleanOrNull(),
    submittedOn = submittedOn?.let(Instant::fromEpochMilliseconds),
    submission = submission,
    submissionResponse = submissionResponse,
    createdOn = createdOn?.let(Instant::fromEpochMilliseconds),
    updatedOn = updatedOn?.let(Instant::fromEpochMilliseconds),
    uploadTime = uploadTime?.let(Instant::fromEpochMilliseconds),
)

fun FccSubmission.toRow(): FccSubmissionEntity = FccSubmissionEntity(
    id = id,
    challengeDataId = challengeDataId,
    contactName = contactName,
    contactEmail = contactEmail,
    contactPhone = contactPhone,
    deviceTimestamp = deviceTimestamp?.toEpochMilliseconds(),
    serverTimestamp = serverTimestamp?.toEpochMilliseconds(),
    sourceIp = sourceIp,
    sourcePort = sourcePort?.toLong(),
    deviceId = deviceId,
    deviceImei = deviceImei,
    deviceTac = deviceTac,
    deviceType = deviceType,
    deviceManufacturer = deviceManufacturer,
    deviceModel = deviceModel,
    deviceOsName = deviceOsName,
    appName = appName,
    appVersion = appVersion,
    provider = provider,
    simCountryCode = simCountryCode,
    simNetworkCode = simNetworkCode,
    netCountryCode = netCountryCode,
    netNetworkCode = netNetworkCode,
    inVehicle = inVehicle.toSqlBoolean(),
    externalAntenna = externalAntenna.toSqlBoolean(),
    submitted = submitted.toSqlBoolean(),
    submittedOn = submittedOn?.toEpochMilliseconds(),
    submission = submission,
    submissionResponse = submissionResponse,
    createdOn = createdOn?.toEpochMilliseconds(),
    updatedOn = updatedOn?.toEpochMilliseconds(),
    uploadTime = uploadTime?.toEpochMilliseconds(),
)
